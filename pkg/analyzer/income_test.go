func TestAdultIncomeFeatures(t *testing.T) {
	raw := []byte("39, ?, 77516, Bachelors, 13, Never-married, Adm-clerical, Not-in-family, White, Male, 2174, 0, 40, United-States, <=50K")
	x, err := AdultFeatures(raw)
	if err != nil || len(x) != incomeTransform.Dimension {
		t.Fatal(err)
	}
	y, err := AdultFeatures(bytes.Replace(raw, []byte("<=50K"), []byte(">50K."), 1))
	if err != nil || !reflect.DeepEqual(x, y) {
		t.Fatal("label affected features", err)
	}
	unknown, err := AdultFeatures(bytes.Replace(raw, []byte("39, ?"), []byte("39, unseen-category"), 1))
	if err != nil {
		t.Fatal(err)
	}
	offset := len(incomeTransform.NumericColumns)
	var sum float64
	for _, v := range unknown[offset : offset+len(incomeTransform.Categories[0])] {
		sum += v
	}
	if sum != 0 {
		t.Fatal("unknown category must be ignored")
	}
	missing, err := AdultFeatures(bytes.Replace(raw, []byte("39,"), []byte("?,"), 1))
	if err != nil || missing[0] != (incomeTransform.Medians[0]-incomeTransform.Means[0])/incomeTransform.Scales[0] {
		t.Fatal("numeric missing value", err)
	}
	p := Parameters{Task: AdultIncome, Weights: make([]float64, incomeTransform.Dimension)}
	result, err := Analyze([][]byte{raw}, p)
	if err != nil || string(result) != `{"count":1,"above_threshold":0}` {
		t.Fatal("threshold equality is negative", string(result), err)
	}
	p.Weights = p.Weights[:1]
	if _, err = Analyze([][]byte{raw}, p); err == nil {
		t.Fatal("accepted wrong feature dimension")
	}
}

// This reference is generated by scikit-learn, independently of the Go parser,
// transform and dot product. Compare every score and label, not just the count.
func TestAdultIncomeOfficialReference(t *testing.T) {
	base := "../../data/adult/classification/"
	content, err := os.ReadFile(base + "test.csv")
	if os.IsNotExist(err) {
		t.Skip("prepare the fixed T2 training artifacts for full reference validation")
	}
	if err != nil {
		t.Fatal(err)
	}
	read := func(name string, out any) {
		t.Helper()
		b, e := os.ReadFile(base + name)
		if e != nil {
			t.Fatal(e)
		}
		if e = json.Unmarshal(b, out); e != nil {
			t.Fatal(e)
		}
	}
	var p Parameters
	read("parameters.json", &p)
	transform, err := os.ReadFile(base + "transform.json")
	if err != nil || !bytes.Equal(transform, adultTransformJSON) {
		t.Fatal("reviewed transform does not match the fixed model artifacts", err)
	}
	var ref struct {
		TestSHA256  string    `json:"test_sha256"`
		Scores      []float64 `json:"scores"`
		Predictions []int     `json:"predictions"`
		Count       uint64    `json:"count"`
		Above       uint64    `json:"above_threshold"`
	}
	read("reference.json", &ref)
	h := protocol.H(content)
	if hex.EncodeToString(h[:]) != ref.TestSHA256 {
		t.Fatal("test order/hash mismatch")
	}
	rows, err := ReadAdultRows(bytes.NewReader(content), 0)
	if err != nil || len(rows) != 16281 || len(ref.Scores) != len(rows) || len(ref.Predictions) != len(rows) {
		t.Fatal("invalid reference dimensions", err)
	}
	for i, row := range rows {
		x, e := AdultFeatures(row)
		if e != nil {
			t.Fatal(e)
		}
		score := p.Bias
		for j, v := range x {
			score += v * p.Weights[j]
		}
		if math.Abs(score-ref.Scores[i]) > 1e-10*(1+math.Abs(ref.Scores[i])) {
			t.Fatalf("score differs at row %d: %.17g vs %.17g", i, score, ref.Scores[i])
		}
		if (score > p.Threshold) != (ref.Predictions[i] == 1) {
			t.Fatalf("prediction differs at row %d", i)
		}
	}
	out, err := Analyze(rows, p)
	if err != nil {
		t.Fatal(err)
	}
	var result Result
	if err = json.Unmarshal(out, &result); err != nil || result.Count != ref.Count || result.Above != ref.Above {
		t.Fatal("aggregate mismatch", result, err)
	}
}
